import type {
  MetadataRoute,
} from "next";

const BASE_URL =
  "https://luna-astralis.app";

export default function robots():
  MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",

        allow: "/",

        disallow: [
          /*
          |--------------------------------------------------------------------------
          | API
          |--------------------------------------------------------------------------
          */

          "/api/",

          /*
          |--------------------------------------------------------------------------
          | Développement
          |--------------------------------------------------------------------------
          */

          "/dev/",
          "/_next/",

          /*
          |--------------------------------------------------------------------------
          | Paiement
          |--------------------------------------------------------------------------
          */

          "/checkout",
          "/report-success",

          /*
          |--------------------------------------------------------------------------
          | Pages techniques futures
          |--------------------------------------------------------------------------
          */

          "/success",
          "/cancel",
        ],
      },
    ],

    sitemap:
      `${BASE_URL}/sitemap.xml`,

    host:
      BASE_URL,
  };
}
